function drawHeader(pen: Pen, card: ReportCardData, logo: PDFImage | null) {
  const top = 34;

  if (logo) {
    try {
      const height = 52;
      const width = (logo.width / logo.height) * height;

      pen.page.drawImage(logo, {
        x: LEFT,
        y: PAGE_HEIGHT - top - height,
        width,
        height,
      });
    } catch {
      /* a missing logo must never break the report card */
    }
  }

  const centerX = LEFT;
  const centerWidth = CONTENT_WIDTH;

  if (SCHOOL_PROFILE.ministry) {
    drawText(pen, SCHOOL_PROFILE.ministry, {
      x: centerX,
      top: top - 2,
      size: 6.8,
      color: COLORS.muted,
      width: centerWidth,
      align: "center",
    });
  }

  drawText(pen, SCHOOL_PROFILE.name.toUpperCase(), {
    x: centerX,
    top: top + 8,
    size: 14.5,
    font: pen.fonts.bold,
    color: COLORS.brand,
    width: centerWidth,
    align: "center",
  });

  const addressLine = [
    SCHOOL_PROFILE.address,
    SCHOOL_PROFILE.phone && `Tel: ${SCHOOL_PROFILE.phone}`,
    SCHOOL_PROFILE.email,
  ]
    .filter(Boolean)
    .join("  ·  ");

  if (addressLine) {
    drawText(pen, addressLine, {
      x: centerX,
      top: top + 26,
      size: 7,
      color: COLORS.muted,
      width: centerWidth,
      align: "center",
    });
  }

  if (SCHOOL_PROFILE.motto) {
    drawText(pen, `"${SCHOOL_PROFILE.motto}"`, {
      x: centerX,
      top: top + 37,
      size: 7,
      font: pen.fonts.italic,
      color: COLORS.muted,
      width: centerWidth,
      align: "center",
    });
  }

  /* academic context on the right of the letterhead */

  drawText(pen, `Academic Year: ${card.classroom.academicYearName}`, {
    x: RIGHT - 150,
    top: top + 4,
    size: 7.6,
    font: pen.fonts.bold,
    width: 150,
    align: "right",
  });

  drawText(pen, `Term: ${card.term.name}`, {
    x: RIGHT - 150,
    top: top + 15,
    size: 7.6,
    font: pen.fonts.bold,
    width: 150,
    align: "right",
  });

  /* title band */

  const bandTop = top + 50;
  const bandHeight = 17;

  drawBox(pen, {
    left: LEFT,
    top: bandTop,
    width: CONTENT_WIDTH,
    height: bandHeight,
    fill: COLORS.brand,
  });

  drawText(pen, "TERM REPORT CARD", {
    x: LEFT,
    top: bandTop + 4.5,
    size: 9.5,
    font: pen.fonts.bold,
    color: COLORS.white,
    width: CONTENT_WIDTH,
    align: "center",
  });

  return bandTop + bandHeight + 9;
}

function drawStudentBlock(pen: Pen, card: ReportCardData, top: number) {
  const height = 76;
  const half = CONTENT_WIDTH / 2;

  drawBox(pen, {
    left: LEFT,
    top,
    width: CONTENT_WIDTH,
    height,
    fill: COLORS.bandFill,
    border: COLORS.rule,
  });

  pen.page.drawLine({
    start: { x: LEFT + half, y: PAGE_HEIGHT - top },
    end: { x: LEFT + half, y: PAGE_HEIGHT - top - height },
    thickness: 0.4,
    color: COLORS.rule,
  });

  const rows = [
    [
      ["Student's Name", card.student.fullName],
      ["Matricule", card.student.matricule],
    ],
    [
      ["Class", card.classroom.name],
      ["Section", card.classroom.sectionName ?? "—"],
    ],
    [
      [
        "Parent / Guardian",
        card.student.parentName ?? "Not linked",
      ],
      ["Class size", `${card.class.size} students`],
    ],
  ];

  const padding = 8;
  const labelWidth = 78;
  const valueWidth = half - padding * 2 - labelWidth;

  rows.forEach((row, index) => {
    const rowTop = top + 9 + index * 18;

    row.forEach(([label, value], column) => {
      const x = LEFT + column * half + padding;

      drawText(pen, `${label}:`, {
        x,
        top: rowTop,
        size: 7.4,
        color: COLORS.muted,
        width: labelWidth,
      });

      drawText(pen, value, {
        x: x + labelWidth,
        top: rowTop,
        size: 8,
        font: pen.fonts.bold,
        width: valueWidth,
      });
    });
  });

  /* status line — suspended / dismissed students are visibly flagged */

  const statusText = card.student.enrolled
    ? `Status: ACTIVE — enrolled for ${card.classroom.academicYearName}`
    : `Status: ${card.student.statusLabel.toUpperCase()} — historical record, not currently enrolled`;

  drawRule(pen, {
    left: LEFT + 1,
    top: top + height - 16,
    width: CONTENT_WIDTH - 2,
    color: COLORS.rule,
    thickness: 0.4,
  });

  drawText(pen, statusText, {
    x: LEFT + padding,
    top: top + height - 12,
    size: 7.2,
    font: card.student.enrolled ? pen.fonts.regular : pen.fonts.bold,
    color: card.student.enrolled ? COLORS.muted : COLORS.warn,
    width: CONTENT_WIDTH - padding * 2,
  });

  return top + height + 11;
}

