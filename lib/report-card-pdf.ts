/**
 * Report card template — A4 portrait term report card.
 *
 * Structure (kept identical from page to page, close to the printed
 * Cameroonian secondary-school term report card):
 *
 *   ┌ outer double border ──────────────────────────────────────────────┐
 *   │ logo        school header (name, address, motto)      year/term   │
 *   │                  ── TERM REPORT CARD ──                           │
 *   │ student information block (name, matricule, class, parent, rank)  │
 *   │ subjects table: per sequence CA1 / CA2 / Exam / Average, then      │
 *   │                 term average, coefficient points, grade, remark    │
 *   │ term summary + class performance + attendance                      │
 *   │ remarks (class teacher, principal) + promotion decision            │
 *   │ signatures (class teacher, academic master, principal) + date      │
 *   │ footer: generated by GradeFlow · page x of y                       │
 *   └───────────────────────────────────────────────────────────────────┘
 *
 * Everything printed comes from ReportCardData, which is read from
 * PostgreSQL. Values the school itself must supply (letterhead, motto,
 * principal's name) come from the SCHOOL_* environment variables — see
 * SCHOOL_PROFILE in lib/report-card.ts.
 */

