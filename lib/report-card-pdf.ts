function drawSignatures(pen: Pen, top: number) {
  const blocks = [
    "Class Teacher",
    SCHOOL_PROFILE.academicMasterName
      ? `Academic Master (${SCHOOL_PROFILE.academicMasterName})`
      : "Academic Master",
    SCHOOL_PROFILE.principalName
      ? `Principal (${SCHOOL_PROFILE.principalName})`
      : "Principal",
  ];

  const width = CONTENT_WIDTH / blocks.length;

  blocks.forEach((label, index) => {
    const x = LEFT + index * width;

    drawText(pen, label, {
      x: x + 4,
      top,
      size: 6.8,
      color: COLORS.muted,
      width: width - 8,
      align: "center",
    });

    drawRule(pen, {
      left: x + 10,
      top: top + 22,
      width: width - 20,
      color: COLORS.ink,
      thickness: 0.6,
    });

    drawText(pen, "Signature & date", {
      x: x + 4,
      top: top + 25,
      size: 6,
      color: COLORS.muted,
      width: width - 8,
      align: "center",
    });
  });

  return top + 36;
}

/* =========================================================
   PAGE COMPOSITION
========================================================= */

function drawReportCardPage(
  doc: PDFDocument,
  card: ReportCardData,
  fonts: Fonts,
  logo: PDFImage | null,
  pageNumber: number,
  totalPages: number
) {
  const page = doc.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
  const pen: Pen = { page, fonts };

  drawPageFrame(pen);

  let top = drawHeader(pen, card, logo);

  top = drawStudentBlock(pen, card, top);

  const columns = columnsFor(card);

  top = tableHeader(pen, card, columns, top);

  card.subjects.forEach((line, index) => {
    top = drawSubjectRow(pen, card, line, columns, top, index % 2 === 1);
  });

  top = drawTotalsRow(pen, card, columns, top);

  top += 12;

  const half = (CONTENT_WIDTH - 8) / 2;

  const summaryHeight = 12 + 4 * 14 + 6;

  drawSummaryBlock(
    pen,
    "TERM SUMMARY",
    [
      ["Total coefficients", String(card.totals.coefficients)],
      ["Total points (Coef × Avg)", average(card.totals.points)],
      ["Term average / 20", average(card.totals.average)],
      ["Grade", card.totals.grade ?? "—"],
    ],
    { left: LEFT, top, width: half, height: summaryHeight }
  );

  drawSummaryBlock(
    pen,
    "CLASS PERFORMANCE",
    [
      ["Class average", average(card.class.average)],
      ["Highest average", average(card.class.highest)],
      ["Lowest average", average(card.class.lowest)],
      [
        "Position",
        card.class.position ? `${card.class.position} of ${card.class.ranked}` : "—",
      ],
    ],
    { left: LEFT + half + 8, top, width: half, height: summaryHeight }
  );

  top += summaryHeight + 8;

  const attendanceHeight = 12 + 4 * 14 + 6;

  drawSummaryBlock(
    pen,
    "ATTENDANCE / DISCIPLINE (TERM)",
    [
      ["Present", `${card.attendance.PRESENT} h`],
      ["Absent", `${card.attendance.ABSENT} h`],
      ["Late", `${card.attendance.LATE} h`],
      ["Excused", `${card.attendance.EXCUSED} h`],
    ],
    { left: LEFT, top, width: half, height: attendanceHeight }
  );

  drawSummaryBlock(
    pen,
    "ENROLMENT",
    [
      ["Academic year", card.classroom.academicYearName],
      ["Term", card.term.name],
      ["Status", card.student.statusLabel],
      ["Attendance rate", card.attendance.rate === null ? "—" : `${card.attendance.rate}%`],
    ],
    { left: LEFT + half + 8, top, width: half, height: attendanceHeight }
  );

  top += attendanceHeight + 8;

  top = drawRemarksBlock(pen, card, top);

  top = drawGradingLegend(pen, top);

  top = drawSignatures(pen, top);

  /* footer */

  drawRule(pen, { left: LEFT, top, width: CONTENT_WIDTH, color: COLORS.rule });

  drawText(
    pen,
    `Generated by GradeFlow from the marks, attendance and results stored in the school database on ${shortDate(card.generatedAt)}.`,
    {
      x: LEFT,
      top: top + 4,
      size: 6.2,
      color: COLORS.muted,
      width: CONTENT_WIDTH * 0.72,
    }
  );

  drawText(pen, `Page ${pageNumber} of ${totalPages}`, {
    x: LEFT + CONTENT_WIDTH * 0.72,
    top: top + 4,
    size: 6.2,
    color: COLORS.muted,
    width: CONTENT_WIDTH * 0.28,
    align: "right",
  });
}

async function loadFonts(doc: PDFDocument): Promise<Fonts> {
  return {
    regular: await doc.embedFont(StandardFonts.Helvetica),
    bold: await doc.embedFont(StandardFonts.HelveticaBold),
    italic: await doc.embedFont(StandardFonts.HelveticaOblique),
    boldItalic: await doc.embedFont(StandardFonts.HelveticaBoldOblique),
  };
}

