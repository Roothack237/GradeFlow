type Column = { key: string; label: string; width: number; align?: "left" | "center" | "right" };

function columnsFor(card: ReportCardData): Column[] {
  const sequenceColumns = card.sequences.flatMap((sequence) => [
    {
      key: `${sequence.id}-ca1`,
      label: "CA1",
      width: 25,
      align: "center" as const,
    },
    {
      key: `${sequence.id}-ca2`,
      label: "CA2",
      width: 25,
      align: "center" as const,
    },
    {
      key: `${sequence.id}-exam`,
      label: "Exam",
      width: 27,
      align: "center" as const,
    },
    {
      key: `${sequence.id}-avg`,
      label: "Avg",
      width: 29,
      align: "center" as const,
    },
  ]);

  const fixed: Column[] = [
    { key: "subject", label: "SUBJECT", width: 0, align: "left" },
    { key: "coefficient", label: "Coef", width: 26, align: "center" },
    ...sequenceColumns,
    { key: "termAverage", label: "Term Avg", width: 38, align: "center" },
    { key: "points", label: "Coef×Avg", width: 40, align: "center" },
    { key: "grade", label: "Grade", width: 28, align: "center" },
    { key: "remark", label: "Remarks", width: 0, align: "left" },
  ];

  const fixedWidth = fixed.reduce((sum, column) => sum + column.width, 0);
  const remaining = CONTENT_WIDTH - fixedWidth;
  const remarkWidth = Math.max(72, Math.min(110, remaining * 0.42));
  const subjectWidth = remaining - remarkWidth;

  return fixed.map((column) => {
    if (column.key === "subject") return { ...column, width: subjectWidth };
    if (column.key === "remark") return { ...column, width: remarkWidth };
    return column;
  });
}

function tableHeader(pen: Pen, card: ReportCardData, columns: Column[], top: number) {
  const groupHeight = 11;
  const labelHeight = 12;
  const totalHeight = groupHeight + labelHeight;

  /* group header */

  drawBox(pen, {
    left: LEFT,
    top,
    width: CONTENT_WIDTH,
    height: groupHeight,
    fill: COLORS.groupFill,
    border: COLORS.rule,
    borderWidth: 0.5,
  });

  let x = LEFT;

  drawText(pen, `SUBJECTS — ${card.term.name.toUpperCase()}`, {
    x: LEFT + 4,
    top: top + 2.6,
    size: 6.6,
    font: pen.fonts.bold,
    color: COLORS.brand,
    width: columns[0].width,
  });

  x = LEFT + columns[0].width + columns[1].width;

  card.sequences.forEach((sequence) => {
    const width = columns
      .filter((column) => column.key.startsWith(`${sequence.id}-`))
      .reduce((sum, column) => sum + column.width, 0);

    drawText(pen, `${sequence.name.toUpperCase()} (out of 20)`, {
      x,
      top: top + 2.6,
      size: 6.4,
      font: pen.fonts.bold,
      color: COLORS.brand,
      width,
      align: "center",
    });

    x += width;
  });

  drawText(pen, "TERM RESULT", {
    x: x + 34,
    top: top + 2.6,
    size: 6.4,
    font: pen.fonts.bold,
    color: COLORS.brand,
    width: columns
      .filter((column) =>
        ["termAverage", "points", "grade"].includes(column.key)
      )
      .reduce((sum, column) => sum + column.width, 0),
    align: "center",
  });

  /* column labels */

  const labelTop = top + groupHeight;

  drawBox(pen, {
    left: LEFT,
    top: labelTop,
    width: CONTENT_WIDTH,
    height: labelHeight,
    fill: COLORS.headerFill,
    border: COLORS.rule,
    borderWidth: 0.5,
  });

  let labelX = LEFT;

  for (const column of columns) {
    drawText(pen, column.label, {
      x: labelX + 2,
      top: labelTop + 3.4,
      size: 5.9,
      font: pen.fonts.bold,
      width: column.width - 6,
      align: column.align === "left" ? "left" : "center",
    });

    labelX += column.width;
  }

  return top + totalHeight;
}

function subjectCells(card: ReportCardData, line: SubjectLine): Record<string, string> {
  const cells: Record<string, string> = {
    subject: line.subject,
    coefficient: String(line.coefficient),
    termAverage: average(line.average),
    points: average(line.points),
    grade: line.grade ?? "—",
    remark: line.remark ?? "—",
  };

  for (const sequence of line.sequences) {
    cells[`${sequence.sequenceId}-ca1`] = mark(sequence.ca1);
    cells[`${sequence.sequenceId}-ca2`] = mark(sequence.ca2);
    cells[`${sequence.sequenceId}-exam`] = mark(sequence.exam);
    cells[`${sequence.sequenceId}-avg`] = average(sequence.average);
  }

  return cells;
}

function drawSubjectRow(
  pen: Pen,
  card: ReportCardData,
  line: SubjectLine,
  columns: Column[],
  top: number,
  striped: boolean
) {
  const height = 25;

  drawBox(pen, {
    left: LEFT,
    top,
    width: CONTENT_WIDTH,
    height,
    fill: striped ? COLORS.zebra : COLORS.white,
    border: COLORS.rule,
    borderWidth: 0.4,
  });

  const cells = subjectCells(card, line);

  let x = LEFT;

  for (const column of columns) {
    if (column.key === "subject") {
      drawText(pen, cells.subject, {
        x: x + 4,
        top: top + 4,
        size: 7.8,
        font: pen.fonts.bold,
        width: column.width - 8,
      });

      if (line.teacher) {
        drawText(pen, `Teacher: ${line.teacher}`, {
          x: x + 4,
          top: top + 14.5,
          size: 6.1,
          font: pen.fonts.italic,
          color: COLORS.muted,
          width: column.width - 8,
        });
      }

      x += column.width;
      continue;
    }

    drawText(pen, cells[column.key] ?? "—", {
      x: x + 3,
      top: top + 8.5,
      size: 7.4,
      width: column.width - 6,
      align: column.align === "left" ? "left" : "center",
    });

    x += column.width;
  }

  return top + height;
}

function drawTotalsRow(
  pen: Pen,
  card: ReportCardData,
  columns: Column[],
  top: number
) {
  const height = 20;

  drawBox(pen, {
    left: LEFT,
    top,
    width: CONTENT_WIDTH,
    height,
    fill: COLORS.headerFill,
    border: COLORS.rule,
    borderWidth: 0.5,
  });

  drawText(pen, "TOTAL", {
    x: LEFT + 4,
    top: top + 6.5,
    size: 7.8,
    font: pen.fonts.bold,
    width: columns[0].width - 8,
  });

  let x = LEFT + columns[0].width;

  drawText(pen, String(card.totals.coefficients), {
    x: x + 3,
    top: top + 6.5,
    size: 7.8,
    font: pen.fonts.bold,
    width: columns[1].width - 6,
    align: "center",
  });

  x += columns[1].width;

  /* One total per sequence: the points earned (Σ average × coefficient),
     which is the figure that feeds the term average. */
  card.sequences.forEach((sequence) => {
    const sequenceWidth = columns
      .filter((column) => column.key.startsWith(`${sequence.id}-`))
      .reduce((sum, column) => sum + column.width, 0);

    const recorded = card.subjects
      .map((line) => ({
        coefficient: line.coefficient,
        mark: line.sequences.find((entry) => entry.sequenceId === sequence.id),
      }))
      .filter(
        (row): row is { coefficient: number; mark: SequenceMark } =>
          Boolean(row.mark) && row.mark?.average !== null
      );

    const points = recorded.reduce(
      (sum, row) => sum + (row.mark.average ?? 0) * row.coefficient,
      0
    );

    const coefficients = recorded.reduce(
      (sum, row) => sum + row.coefficient,
      0
    );

    const sequenceAverage = coefficients ? points / coefficients : null;

    drawText(
      pen,
      recorded.length
        ? `${points.toFixed(2)} pts  (avg ${average(sequenceAverage)})`
        : "—",
      {
        x,
        top: top + 6.5,
        size: 6.6,
        font: pen.fonts.bold,
        color: COLORS.brand,
        width: sequenceWidth,
        align: "center",
      }
    );

    x += sequenceWidth;
  });

  const termAverageColumn = columns.find((column) => column.key === "termAverage");
  const pointsColumn = columns.find((column) => column.key === "points");
  const gradeColumn = columns.find((column) => column.key === "grade");

  drawText(pen, average(card.totals.average), {
    x: x + 3,
    top: top + 6.5,
    size: 8,
    font: pen.fonts.bold,
    width: (termAverageColumn?.width ?? 38) - 6,
    align: "center",
  });
  x += termAverageColumn?.width ?? 38;

  drawText(pen, average(card.totals.points), {
    x: x + 3,
    top: top + 6.5,
    size: 7.8,
    font: pen.fonts.bold,
    width: (pointsColumn?.width ?? 40) - 6,
    align: "center",
  });
  x += pointsColumn?.width ?? 40;

  drawText(pen, card.totals.grade ?? "—", {
    x: x + 3,
    top: top + 6.5,
    size: 8,
    font: pen.fonts.bold,
    color: COLORS.brand,
    width: (gradeColumn?.width ?? 28) - 6,
    align: "center",
  });
  x += gradeColumn?.width ?? 28;

  drawText(pen, `Pos. ${card.class.position ?? "—"}/${card.class.ranked}`, {
    x: x + 4,
    top: top + 6.5,
    size: 6.8,
    font: pen.fonts.bold,
    width: RIGHT - x - 4,
  });

  return top + height;
}

