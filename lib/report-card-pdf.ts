let cachedLogo: Uint8Array | null | undefined;

/**
 * Reads the school logo once per process. The paths are static literals so
 * the production build can trace them; when no logo file exists the report
 * card header is simply drawn without one.
 */
async function loadLogo(): Promise<Uint8Array | null> {
  if (cachedLogo !== undefined) return cachedLogo;

  cachedLogo = null;

  try {
    cachedLogo = await readFile(
      path.join(process.cwd(), "public", "images", "logo.png")
    );

    return cachedLogo;
  } catch {
    /* the PNG logo is missing — try the JPEG one */
  }

  try {
    cachedLogo = await readFile(
      path.join(process.cwd(), "public", "images", "logo.jpg")
    );
  } catch {
    cachedLogo = null;
  }

  return cachedLogo;
}

/** Embeds the logo once per PDF document and reuses it on every page. */
async function embedLogo(doc: PDFDocument): Promise<PDFImage | null> {
  const bytes = await loadLogo();

  if (!bytes) return null;

  try {
    return await doc.embedPng(bytes);
  } catch {
    return null;
  }
}

