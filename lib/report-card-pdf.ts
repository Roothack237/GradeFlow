type Fonts = {
  regular: PDFFont;
  bold: PDFFont;
  italic: PDFFont;
  boldItalic: PDFFont;
};

type Pen = {
  page: PDFPage;
  fonts: Fonts;
};

function baseline(top: number, size: number) {
  return PAGE_HEIGHT - top - size * 0.82;
}

function drawText(
  pen: Pen,
  value: string,
  options: {
    x: number;
    top: number;
    size: number;
    font?: PDFFont;
    color?: RGB;
    width?: number;
    align?: "left" | "center" | "right";
  }
) {
  const font = options.font ?? pen.fonts.regular;
  const text = options.width
    ? fitText(value, font, options.size, options.width)
    : safeText(value);

  if (!text) return;

  let x = options.x;

  if (options.align && options.width) {
    const textWidth = font.widthOfTextAtSize(text, options.size);

    if (options.align === "center") x = options.x + (options.width - textWidth) / 2;
    if (options.align === "right") x = options.x + options.width - textWidth;
  }

  pen.page.drawText(text, {
    x,
    y: baseline(options.top, options.size),
    size: options.size,
    font,
    color: options.color ?? COLORS.ink,
  });
}

function drawBox(
  pen: Pen,
  box: {
    left: number;
    top: number;
    width: number;
    height: number;
    fill?: RGB;
    border?: RGB;
    borderWidth?: number;
  }
) {
  pen.page.drawRectangle({
    x: box.left,
    y: PAGE_HEIGHT - box.top - box.height,
    width: box.width,
    height: box.height,
    color: box.fill,
    borderColor: box.border,
    borderWidth: box.border ? (box.borderWidth ?? 0.6) : undefined,
  });
}

function drawRule(
  pen: Pen,
  options: {
    left: number;
    top: number;
    width: number;
    color?: RGB;
    thickness?: number;
  }
) {
  pen.page.drawLine({
    start: { x: options.left, y: PAGE_HEIGHT - options.top },
    end: { x: options.left + options.width, y: PAGE_HEIGHT - options.top },
    thickness: options.thickness ?? 0.6,
    color: options.color ?? COLORS.rule,
  });
}

