/** Renders one student's report card as an A4 portrait PDF. */
export async function renderReportCardPdf(
  card: ReportCardData
): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const fonts = await loadFonts(doc);
  const logo = await embedLogo(doc);

  doc.setTitle(
    `Report card — ${card.student.fullName} — ${card.term.name} ${card.classroom.academicYearName}`
  );
  doc.setAuthor(SCHOOL_PROFILE.name);
  doc.setSubject(`${card.classroom.name} · ${card.term.name}`);

  drawReportCardPage(doc, card, fonts, logo, 1, 1);

  return doc.save();
}

/**
 * Renders a class set of report cards: one page per student, in the order
 * given (the class list order), inside a single PDF document.
 */
export async function renderReportCardsPdf(
  cards: ReportCardData[]
): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const fonts = await loadFonts(doc);
  const logo = await embedLogo(doc);

  doc.setTitle(
    cards.length
      ? `${cards[0].classroom.name} report cards — ${cards[0].term.name} ${cards[0].classroom.academicYearName}`
      : "Report cards"
  );
  doc.setAuthor(SCHOOL_PROFILE.name);

  for (let index = 0; index < cards.length; index += 1) {
    drawReportCardPage(doc, cards[index], fonts, logo, index + 1, cards.length);
  }

  return doc.save();
}

/** File name used for a class set, e.g. Form3A_Report_Cards_2026_2027.pdf */
export function classReportCardFileName(
  classroomName: string,
  academicYearName: string
) {
  const clean = (value: string) => value.replace(/[^A-Za-z0-9]+/g, "_");

  return `${clean(classroomName)}_Report_Cards_${clean(academicYearName.replace("/", "_"))}.pdf`;
}

/** File name used for one student, e.g. Report_Card_John_Doe_First_Term.pdf */
export function studentReportCardFileName(card: ReportCardData) {
  const clean = (value: string) => value.replace(/[^A-Za-z0-9]+/g, "_");

  return `Report_Card_${clean(card.student.fullName)}_${clean(card.term.name)}_${clean(
    card.classroom.academicYearName.replace("/", "_")
  )}.pdf`;
}
